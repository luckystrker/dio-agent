// Декодирование windows-1251 для web_fetch (блок 18.9): страницы в cp1251
// уходили модели как U+FFFD-мусор. Мини-таблица внутри пакета — без внешних
// зависимостей; покрывает старшую половину (0x80–0xFF), ASCII переходит как
// есть, не назначенные в cp1251 байты (0x98) — U+FFFD. Источник — каноническая
// таблица Unicode/IANA windows-1251.
package web

import "strings"

// cp1251Hi — отображение байтов 0x80–0xFF на руны (индекс = байт − 0x80).
var cp1251Hi = [128]rune{
	0x0402, 0x0403, 0x201A, 0x0453, 0x201E, 0x2026, 0x2020, 0x2021, // 80-87: Ђ Ѓ ‚ ѓ „ … † ‡
	0x20AC, 0x2030, 0x0409, 0x2039, 0x040A, 0x040C, 0x040B, 0x040F, // 88-8F: € ‰ Љ ‹ Њ Ќ Ћ Џ
	0x0452, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2013, 0x2014, // 90-97: ђ ' ' " " • – —
	0xFFFD, 0x2122, 0x0459, 0x203A, 0x045A, 0x045C, 0x045B, 0x045F, // 98-9F: — ™ љ › њ ќ ћ џ
	0x00A0, 0x00A1, 0x00A2, 0x00A3, 0x20A4, 0x20BD, 0x00A6, 0x00A7, // A0-A7: nbsp ¡ ¢ £ ₤ ₽ ¦ §
	0x0401, 0x00A9, 0x00AA, 0x00AB, 0x00AC, 0x00AD, 0x00AE, 0x00AF, // A8-AF: Ё © ª « ¬ мягкий-перенос ® ¯
	0x00B0, 0x00B1, 0x00B2, 0x00B3, 0x00B4, 0x00B5, 0x00B6, 0x00B7, // B0-B7: ° ± ² ³ ´ µ ¶ ·
	0x0451, 0x2116, 0x00BA, 0x00BB, 0x00BC, 0x00BD, 0x00BE, 0x00BF, // B8-BF: ё № º » ¼ ½ ¾ ¿
	0x0410, 0x0411, 0x0412, 0x0413, 0x0414, 0x0415, 0x0416, 0x0417, // C0-C7: А Б В Г Д Е Ж З
	0x0418, 0x0419, 0x041A, 0x041B, 0x041C, 0x041D, 0x041E, 0x041F, // C8-CF: И Й К Л М Н О П
	0x0420, 0x0421, 0x0422, 0x0423, 0x0424, 0x0425, 0x0426, 0x0427, // D0-D7: Р С Т У Ф Х Ц Ч
	0x0428, 0x0429, 0x042A, 0x042B, 0x042C, 0x042D, 0x042E, 0x042F, // D8-DF: Ш Щ Ъ Ы Ь Э Ю Я
	0x0430, 0x0431, 0x0432, 0x0433, 0x0434, 0x0435, 0x0436, 0x0437, // E0-E7: а б в г д е ж з
	0x0438, 0x0439, 0x043A, 0x043B, 0x043C, 0x043D, 0x043E, 0x043F, // E8-EF: и й к л м н о п
	0x0440, 0x0441, 0x0442, 0x0443, 0x0444, 0x0445, 0x0446, 0x0447, // F0-F7: р с т у ф х ц ч
	0x0448, 0x0449, 0x044A, 0x044B, 0x044C, 0x044D, 0x044E, 0x044F, // F8-FF: ш щ ъ ы ь э ю я
}

// decodeWindows1251 — cp1251-байты в UTF-8 строку.
func decodeWindows1251(b []byte) string {
	var sb strings.Builder
	sb.Grow(len(b)) // кириллица в UTF-8 вдвое длиннее — Grow оценочный, не лимит
	for _, c := range b {
		if c < 0x80 {
			sb.WriteRune(rune(c))
			continue
		}
		sb.WriteRune(cp1251Hi[c-0x80])
	}
	return sb.String()
}
